-- Run with supabase test db against a disposable local database only.
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;
SET search_path = public, extensions;
SELECT plan(15);
INSERT INTO auth.users (id, email) VALUES ('fc111111-1111-4111-8111-111111111111', 'comp-fixture@example.invalid');
INSERT INTO public.profiles (id) VALUES ('fc111111-1111-4111-8111-111111111111') ON CONFLICT (id) DO NOTHING;
SELECT set_config('request.jwt.claim.sub', 'fc111111-1111-4111-8111-111111111111', true);
CREATE TEMP TABLE comp_fixture (id uuid);
INSERT INTO comp_fixture SELECT public.ensure_user_farm();
GRANT SELECT ON comp_fixture TO authenticated;
SELECT ok((SELECT relrowsecurity FROM pg_class WHERE oid = 'public.farm_comps'::regclass), 'RLS enabled');
SELECT ok(NOT has_table_privilege('authenticated', 'public.farm_comps', 'SELECT'), 'client cannot read reasons');
SELECT ok(NOT has_table_privilege('authenticated', 'public.farm_comps', 'INSERT'), 'client cannot insert');
SELECT ok(NOT has_table_privilege('authenticated', 'public.farm_comps', 'UPDATE'), 'client cannot update');
SELECT ok(NOT has_table_privilege('authenticated', 'public.farm_comps', 'DELETE'), 'client cannot delete');
SELECT ok(NOT has_function_privilege('anon', 'public.get_farm_comp_status(uuid)', 'EXECUTE'), 'anon cannot execute');
SELECT ok(has_function_privilege('authenticated', 'public.get_farm_comp_status(uuid)', 'EXECUTE'), 'member role can execute');
SELECT ok(NOT has_table_privilege('service_role', 'public.farm_comps', 'DELETE'), 'service uses soft delete');
SET LOCAL ROLE authenticated;
SELECT is((SELECT is_comped FROM public.get_farm_comp_status((SELECT id FROM comp_fixture))), false, 'no comp');
SELECT is((SELECT count(*)::int FROM public.get_farm_comp_status('fc222222-2222-4222-8222-222222222222')), 0, 'other farm hidden');
RESET ROLE;
INSERT INTO public.farm_comps (farm_id, reason, expires_at) SELECT id, 'fixture', now() + interval '1 day' FROM comp_fixture;
SET LOCAL ROLE authenticated;
SELECT ok((SELECT is_comped AND expires_at > now() FROM public.get_farm_comp_status((SELECT id FROM comp_fixture))), 'live expiring comp');
RESET ROLE;
UPDATE public.farm_comps SET expires_at = now() WHERE farm_id = (SELECT id FROM comp_fixture);
SET LOCAL ROLE authenticated;
SELECT is((SELECT is_comped FROM public.get_farm_comp_status((SELECT id FROM comp_fixture))), false, 'expiry boundary excluded');
RESET ROLE;
INSERT INTO public.farm_comps (farm_id, reason) SELECT id, 'permanent fixture' FROM comp_fixture;
SET LOCAL ROLE authenticated;
SELECT ok((SELECT is_comped AND expires_at IS NULL FROM public.get_farm_comp_status((SELECT id FROM comp_fixture))), 'permanent comp');
RESET ROLE;
UPDATE public.farm_comps SET deleted_at = now() WHERE farm_id = (SELECT id FROM comp_fixture);
SET LOCAL ROLE authenticated;
SELECT is((SELECT is_comped FROM public.get_farm_comp_status((SELECT id FROM comp_fixture))), false, 'soft-deleted comps excluded');
RESET ROLE;
SELECT set_config('request.jwt.claim.sub', '', true);
SET LOCAL ROLE authenticated;
SELECT is((SELECT count(*)::int FROM public.get_farm_comp_status((SELECT id FROM comp_fixture))), 0, 'missing identity hidden');
RESET ROLE;
SELECT * FROM finish();
ROLLBACK;
